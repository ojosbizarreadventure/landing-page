			<p>At ojo.io platform, we incorporate artificial intelligence to enhance workflows, improve decision-making, and enable intelligent automation across the platform.</p>
			<p>Our AI capabilities are powered through integrations with trusted third-party AI service providers, including <strong>OpenAI</strong>. These services are used selectively to support features such as contextual recommendations, content assistance, and natural language interactions.</p>
			<p>OJO is designed with a flexible AI architecture, allowing integration with multiple advanced AI providers over time to ensure performance, reliability, and continuous innovation.</p>

			<h2>How AI is Used</h2>
			<p>OJO uses artificial intelligence as an underlying intelligence layer to enhance system responsiveness, contextual understanding, and workflow continuity across the platform.</p>
			<p>Rather than operating as a standalone feature, AI functions within OJO as part of a broader system that interprets inputs, connects relevant data points, and assists in surfacing meaningful outputs in context.</p>
			<p>Depending on usage, AI capabilities may support:</p>
			<ul>
				<li>Interpreting user inputs and system data to improve relevance of outputs</li>
				<li>Assisting with content generation and structured responses</li>
				<li>Enabling natural language interactions within the platform</li>
				<li>Enhancing system-driven suggestions and operational assistance</li>
			</ul>
			<p>These capabilities are designed to augment user workflows while keeping humans in control of all final decisions and actions.</p>

			<h2>Data Handling & Privacy</h2>
			<p>We are committed to responsible and secure data practices in all AI interactions:</p>
			<ul>
				<li><strong>Minimal Data Processing:</strong> Only the necessary data required for a specific AI function is processed.</li>
				<li><strong>No Model Training on Your Data:</strong> Data processed through AI services is not used to train external models.</li>
				<li><strong>Secure Transmission:</strong> All data shared with AI providers is encrypted in transit using industry-standard protocols.</li>
				<li><strong>Isolated Processing:</strong> Customer data is processed independently and is not shared across users or organizations.</li>
			</ul>

			<h2>User Awareness & Control</h2>
			<ul>
				<li>AI-powered features are clearly identifiable within the platform.</li>
				<li>Users maintain full control over whether and how they use AI features.</li>
				<li>AI-generated outputs are presented for review before any action is taken.</li>
			</ul>

			<h2>Limitations of AI</h2>
			<p>While AI enhances efficiency, it may occasionally produce incomplete or inaccurate outputs. Users are encouraged to apply their judgment and validate results where necessary.</p>

			<h2>Continuous Evolution</h2>
			<p>As AI technology evolves, OJO may incorporate additional AI service providers to improve capabilities, ensure redundancy, and deliver better performance. Any significant changes to AI usage will be reflected in this policy.</p>

